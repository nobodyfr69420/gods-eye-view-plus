// Regenerate docs/OVERLAYS.md from the Overlay Library catalog.
// Usage: node scripts/generate-overlay-docs.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { OVERLAY_DEFINITIONS } from '../src/overlayLibrary/definitions.js';
import { OVERLAY_CATEGORIES } from '../src/overlayLibrary/categories.js';

const KIND = {
  imagery: 'Imagery tiles',
  feed: 'Data feed',
  osm: 'OSM (zoomed in)',
  computed: 'Computed',
};
const escape = (text) => String(text).replace(/\|/g, '\\|');

const byKind = {};
for (const def of OVERLAY_DEFINITIONS)
  byKind[def.kind] = (byKind[def.kind] || 0) + 1;

const lines = [
  '# Overlay Library',
  '',
  `<!-- Generated by scripts/generate-overlay-docs.mjs — do not edit by hand. -->`,
  '',
  `**${OVERLAY_DEFINITIONS.length} overlays** in ${OVERLAY_CATEGORIES.length} categories: ` +
    `${byKind.feed || 0} data feeds, ${byKind.imagery || 0} imagery layers, ` +
    `${byKind.osm || 0} OpenStreetMap layers and ${byKind.computed || 0} computed layers. ` +
    'Every one is keyless.',
  '',
  'Open the **OVERLAYS** panel on the left rail (or press **L**; **Shift+L** opens the **STATS** tab). ' +
    'Search, filter by type, open a row for its description, source, legend and opacity, and click any ' +
    'feature on the globe for its details card.',
  '',
  '- **Data feed** overlays come through the local `/api/overlay-feed/<id>` proxy, which only knows the ' +
    'allowlisted feeds in `server/providers/overlayFeeds/feeds.js`, caches every upstream and serves the ' +
    'last good copy when a source is down. Static reference datasets are cached on disk under ' +
    '`.gev-cache/overlay-feeds/` for a week.',
  '- **OSM** overlays decode OpenFreeMap vector tiles (the same keyless OpenMapTiles source the app ' +
    'already uses) for the area around the view center, so they appear when you zoom in.',
  '- **Imagery** overlays drape raster tiles on the globe; on Google Photorealistic 3D they drape on the ' +
    'photoreal tileset.',
  '- **Computed** overlays are calculated in the browser (sun, moon, terminator, grids, range rings).',
  '',
];
for (const category of OVERLAY_CATEGORIES) {
  const defs = OVERLAY_DEFINITIONS.filter((d) => d.category === category.id);
  if (!defs.length) continue;
  lines.push(`## ${category.glyph} ${category.name} (${defs.length})`, '');
  lines.push(
    '| Overlay | What it shows | Source | Type |',
    '| --- | --- | --- | --- |',
  );
  for (const def of defs) {
    const kind =
      KIND[def.kind] +
      (def.refreshMs
        ? ` · every ${Math.round(def.refreshMs / 60000)} min`
        : '');
    lines.push(
      `| **${escape(def.name)}** | ${escape(def.description)} | ${escape(def.source)} | ${kind} |`,
    );
  }
  lines.push('');
}
lines.push(
  '## STATS tab',
  '',
  'Live numbers for the whole app, refreshed every second while the tab is open:',
  '',
  '- headline tiles: overlays on, overlay features drawn, built-in layer objects, render rate, data loaded, errors;',
  '- three-minute trends (render rate, overlay features, built-in layer objects, JavaScript heap where the browser reports it);',
  '- objects per built-in data layer (flights, ships, satellites…) and features per active overlay;',
  '- the library by category, and a **breakdown** of any active overlay (top groups and min/median/mean/max/total of its key value — e.g. nuclear capacity by country);',
  '- sun and moon position, moon phase, and the NOAA planetary K-index for the last 7 days;',
  '- camera, scene and network diagnostics, with **Export stats (JSON)**.',
  '',
);
const target = fileURLToPath(new URL('../docs/OVERLAYS.md', import.meta.url));
writeFileSync(target, `${lines.join('\n')}\n`);
console.log(`Wrote ${target} (${OVERLAY_DEFINITIONS.length} overlays)`);
